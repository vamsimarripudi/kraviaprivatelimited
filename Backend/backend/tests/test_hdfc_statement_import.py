import os
import tempfile

import pytest

fd, path = tempfile.mkstemp(suffix=".db")
os.close(fd)
os.unlink(path)
os.environ["DATABASE_URL"] = f"sqlite:///{path}"
os.environ["APP_ENV"] = "development"
os.environ["AUTH_MODE"] = "bootstrap"

from fastapi.testclient import TestClient
from fastapi import HTTPException

from backend.main import app
from backend.hdfc_statement_import import parse_hdfc_statement

HDFC_CSV = (
    "Date,Narration,Chq./Ref.No.,Value Dt,Withdrawal Amt.,Deposit Amt.,Closing Balance\n"
    '05/11/2025,"Cloud hosting, monthly",HDFC-UTR-501,05/11/2025,"100.20",,"10,000.00"\n'
    '07/11/2025,"Customer receipt",HDFC-UTR-502,07/11/2025,,"200.00","10,200.00"\n'
)


def h(role="FINANCE"):
    return {"X-Office-Actor": f"{role} Reviewer", "X-Office-Role": role}


def bank(c, name="HDFC Bank"):
    response = c.post("/api/v1/banking/accounts", headers=h("OWNER"), json={
        "bank_name": name,
        "account_name": "KRAVIA PRIVATE LIMITED",
        "masked_account": "XXXXXXXX4321",
        "ifsc": "HDFC0000001",
        "purpose": "Corporate current account",
    })
    assert response.status_code == 201, response.text
    return response.json()["id"]


def test_hdfc_export_parser_accepts_quoted_narration_and_preheader():
    header = "Corporate statement generated by HDFC ENet\n\n" + HDFC_CSV
    rows, issues = parse_hdfc_statement(header)
    assert issues == []
    assert len(rows) == 2
    assert rows[0]["description"] == "Cloud hosting, monthly"
    assert rows[0]["amount_paise"] == 10020
    assert rows[0]["direction"] == "DEBIT"
    assert rows[1]["amount_paise"] == 20000
    assert rows[1]["direction"] == "CREDIT"


def test_hdfc_preview_then_explicit_confirmation_and_idempotent_replay():
    with TestClient(app) as client:
        account = bank(client)
        request = {"bank_account_id": account, "csv_text": HDFC_CSV}
        preview = client.post("/api/v1/banking/hdfc/statement/preview", headers=h(), json=request)
        assert preview.status_code == 200, preview.text
        state = preview.json()
        assert state["live_bank_feed"] is False
        assert state["new_rows"] == 2
        assert state["issues"] == []
        assert state["duplicates"] == 0
        assert len(state["digest"]) == 64
        assert all("account_number" not in x for x in state["preview_rows"])
        confirm = client.post("/api/v1/banking/hdfc/statement/confirm", headers=h(),
                              json={**request, "preview_digest": state["digest"], "confirm": True})
        assert confirm.status_code == 200, confirm.text
        assert confirm.json()["imported"] == 2
        replay = client.post("/api/v1/banking/hdfc/statement/confirm", headers=h(),
                             json={**request, "preview_digest": state["digest"], "confirm": True})
        assert replay.status_code == 200
        assert replay.json() == confirm.json()
        records = client.get("/api/v1/banking/transactions", headers=h()).json()
        imported = [x for x in records if x["bank_account_id"] == account]
        assert len(imported) == 2
        assert all(x["source"] == "HDFC_ENET_CSV" for x in imported)
        assert all(x["match_status"] == "UNMATCHED" for x in imported)
        again = client.post("/api/v1/banking/hdfc/statement/preview", headers=h(), json=request)
        assert again.json()["new_rows"] == 0
        assert again.json()["duplicates"] == 2


def test_hdfc_import_never_accepts_unreviewed_or_modified_statement():
    with TestClient(app) as client:
        account = bank(client)
        sample = {"bank_account_id": account, "csv_text": HDFC_CSV}
        preview = client.post("/api/v1/banking/hdfc/statement/preview", headers=h(), json=sample).json()
        modified = HDFC_CSV.replace("200.00", "500.00")
        conflict = client.post("/api/v1/banking/hdfc/statement/confirm", headers=h(),
                               json={"bank_account_id": account, "csv_text": modified,
                                     "preview_digest": preview["digest"], "confirm": True})
        assert conflict.status_code == 409
        bad = client.post("/api/v1/banking/hdfc/statement/confirm", headers=h(),
                          json={**sample, "preview_digest": preview["digest"], "confirm": False})
        assert bad.status_code == 422
        records = client.get("/api/v1/banking/transactions", headers=h()).json()
        assert not any(x["bank_account_id"] == account for x in records)


def test_hdfc_statement_missing_reference_or_invalid_date_is_fail_closed():
    malformed = HDFC_CSV.replace("HDFC-UTR-501", "")
    rows, issues = parse_hdfc_statement(malformed)
    assert len(rows) == 1
    assert issues[0]["row"] == 2
    assert "reference" in issues[0]["reason"].lower()
    with pytest.raises(HTTPException):
        parse_hdfc_statement(HDFC_CSV.replace("Date,Narration", "BadHeader,Narration"))
    rows, issues = parse_hdfc_statement(HDFC_CSV.replace("05/11/2025", "99/99/2025"))
    assert len(rows) == 1
    assert issues and "date" in issues[0]["reason"].lower()
    with pytest.raises(HTTPException):
        parse_hdfc_statement(HDFC_CSV + "\x00")
    with pytest.raises(HTTPException):
        parse_hdfc_statement(HDFC_CSV * 250)


def test_hdfc_banking_requires_hdfc_account_and_finance_permission():
    with TestClient(app) as client:
        non_hdfc = bank(client, "Another Bank")
        request = {"bank_account_id": non_hdfc, "csv_text": HDFC_CSV}
        denied_bank = client.post("/api/v1/banking/hdfc/statement/preview", headers=h(), json=request)
        assert denied_bank.status_code == 422
        denied_role = client.post("/api/v1/banking/hdfc/statement/preview",
                                  headers=h("EMPLOYEE"), json=request)
        assert denied_role.status_code == 403


def test_server_never_persists_an_unmasked_account_number():
    with TestClient(app) as client:
        unmasked = client.post("/api/v1/banking/accounts", headers=h("OWNER"), json={
            "bank_name": "HDFC Bank", "account_name": "KRAVIA PRIVATE LIMITED",
            "masked_account": "1234567890123456", "purpose": "Synthetic test",
        })
        assert unmasked.status_code == 422
        masked = client.post("/api/v1/banking/accounts", headers=h("OWNER"), json={
            "bank_name": "HDFC Bank", "account_name": "KRAVIA PRIVATE LIMITED",
            "masked_account": "XXXXXXXX1234", "purpose": "Synthetic test",
        })
        assert masked.status_code == 201
        assert masked.json()["masked_account"] == "••••1234"
