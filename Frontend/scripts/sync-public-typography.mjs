import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";
import postcss from "postcss";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const marker = "/* PUBLIC TYPOGRAPHY: generated by scripts/sync-public-typography.mjs */";
const modules = ["legal-document", "legal-trust-center", "recruitflow-product-page", "yukta-research", "vorio-market-chart"];
const publicSection = /hero|intro|section|band|portfolio|principles|at-a-glance|purpose|corporate-information|newsroom-shell|article-shell|media-kit|contact-experience|support-portal|detail-shell|footer-brand-row|footer-directory/;
const privateSelector = /office|admin|corporate-workspace|profile-settings|login|content-studio|audit-explorer|support-operations|content-governance/;

function scaled(value, factor) {
  return value.replace(/(\d*\.?\d+)(rem|px|vw|vh)/g, (_, number, unit) => `${Number((Number(number) * factor).toFixed(5))}${unit}`);
}

function compactRules(css, prefix) {
  const output = postcss.root();
  // Match the browser: discard two invalid legacy margin declarations before parsing.
  postcss.parse(css.replaceAll("margin:0 0:.55rem;", "")).walkRules((rule) => {
    const ancestors = [];
    for (let parent = rule.parent; parent?.type !== "root"; parent = parent.parent) {
      if (!parent || parent.type !== "atrule" || parent.name !== "media" || /print/.test(parent.params)) return;
      ancestors.unshift(parent);
    }
    const selectors = postcss.list.comma(rule.selector).filter((selector) => !privateSelector.test(selector));
    if (!selectors.length) return;
    const headingSelectors = selectors.filter((selector) => /(?:^|[\s>+~,(])h[1-3](?:$|[\s>+~.:#\[),])/.test(selector) || /\.ui-card-title$/.test(selector));
    const heading = postcss.rule({ selector: headingSelectors.map((selector) => `${prefix} ${selector}`).join(", ") });
    rule.walkDecls((decl) => {
      if (!headingSelectors.length) return;
      let size = decl.prop === "font-size" ? decl.value : null;
      if (decl.prop === "font") size = decl.value.match(/(?:clamp|min|max)\([^)]*\)|(?:\d*\.?\d+)(?:rem|px|vw)/)?.[0] ?? null;
      if (size) {
        heading.append({ prop: "font-size", value: `max(1rem, ${scaled(size, .75)})` });
        heading.append({ prop: "line-height", value: "1.12" });
      }
      if (["margin", "margin-bottom", "margin-top"].includes(decl.prop)) heading.append({ prop: decl.prop, value: scaled(decl.value, .75) });
    });
    const spacingSelectors = selectors.filter((selector) => publicSection.test(selector));
    const spacing = postcss.rule({ selector: spacingSelectors.map((selector) => `${prefix} ${selector}`).join(", ") });
    rule.walkDecls((decl) => {
      if (spacingSelectors.length && decl.prop === "padding-block") spacing.append({ prop: decl.prop, value: scaled(decl.value, .8) });
    });
    for (const node of [heading, spacing]) {
      if (!node.nodes?.length) continue;
      let outer = node;
      for (const ancestor of [...ancestors].reverse()) outer = postcss.atRule({ name: "media", params: ancestor.params }).append(outer);
      output.append(outer);
    }
  });
  const screen = postcss.atRule({ name: "media", params: "screen" }).append(output.nodes);
  return `${marker}\n/* Display headings: 75% of the source scale; section padding: 80%. Body and controls retain their sizes. */\n${screen.toString()}\n`;
}

writeFileSync(resolve(root, "app/public-typography.css"), compactRules(readFileSync(resolve(root, "app/globals.css"), "utf8"), "body:has(.nav-wrap)"));
for (const name of modules) {
  const path = resolve(root, `components/${name}.module.css`);
  const original = readFileSync(path, "utf8").split(marker)[0].trimEnd();
  writeFileSync(path, `${original}\n\n${compactRules(original, ":global(body:has(.nav-wrap))")}`);
}
console.log("Updated public typography and spacing; internal workspaces and print styles are untouched.");
